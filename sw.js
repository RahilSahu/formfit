/* FormFit service worker: cache the app shell so the image tool works
 * fully offline after the first visit. User files are never cached or
 * transmitted; only the static app files are stored. */
const CACHE = "formfit-v1";
const SHELL = ["./", "./index.html", "./styles.css", "./app.js", "./fit.mjs", "./manifest.webmanifest"];

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  event.respondWith(
    caches.match(event.request).then((hit) => hit || fetch(event.request))
  );
});
